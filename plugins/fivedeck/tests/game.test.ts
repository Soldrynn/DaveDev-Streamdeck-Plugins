test("game process names across builds and games", () => {
  for (const name of ["FiveM_GTAProcess.exe", "FiveM_b3258_GTAProcess.exe", "FiveM_cl2_b3095_GTAProcess.exe", "FiveM_b3407_GameProcess.exe", "RedM_b1491_GTAProcess.exe"]) assert(GAME_PROCESS.test(name), name);
  for (const name of ["FiveM.exe", "FiveM_ChromeBrowser", "notepad.exe", "FiveM_SteamChild.exe"]) assert(!GAME_PROCESS.test(name), name);
});

test("bind detection in fivem.cfg", () => {
  const config = `// generated by CitizenFX\nunbindall\nbind KEYBOARD F24 "exec fxd:/fivedeck.cfg"\nbind KEYBOARD F13 "e dance"\nseta "profile_sfxVolume" "5"\n`;
  assert.deepEqual(bindState(config, "F24"), { state: "installed" });
  assert.deepEqual(bindState(config, "f13"), { state: "conflict", existing: "e dance" });
  assert.deepEqual(bindState(config, "F22"), { state: "missing" });
  assert.deepEqual(bindState(`bind keyboard "F24" "EXEC fxd:/fivedeck.cfg"`, "F24"), { state: "installed" });
});

test("the bridge bind goes right after unbindall and keeps line endings", () => {
  const original = "// generated by CitizenFX\r\nunbindall\r\nbind KEYBOARD F13 \"e dance\"\r\nseta \"a\" \"1\"\r\n";
  const updated = withBridgeBind(original, "F24");
  assert.equal(updated, "// generated by CitizenFX\r\nunbindall\r\nbind KEYBOARD F24 \"exec fxd:/fivedeck.cfg\"\r\nbind KEYBOARD F13 \"e dance\"\r\nseta \"a\" \"1\"\r\n");
  assert.equal(withBridgeBind("", "F23"), "bind KEYBOARD F23 \"exec fxd:/fivedeck.cfg\"\n");
  assert.equal(bindState(updated, "F24").state, "installed");
  assert.equal(bindCommand("F24"), 'bind keyboard F24 "exec fxd:/fivedeck.cfg"');
});

test("hold release lines, chat lines, typed text, and join links", () => {
  assert.deepEqual(releaseLines(["+radiotalk", "e wave", "+vc_ptt extra"]), ["-radiotalk", "-vc_ptt"]);
  assert.equal(chatLine("e dance"), "/e dance");
  assert.equal(chatLine("/me waves"), "/me waves");
  assert.equal(typedText("a\nb"), "a b");
  assert.equal(typedText("x".repeat(500)).length, 400);
  assert.equal(fivemUri({ kind: "join", code: "abc123" }), "fivem://connect/cfx.re/join/abc123");
});

class FakeNative implements NativeInput {
  log: string[] = [];
  foreground = "FiveM_b3258_GTAProcess.exe";
  running = true;
  focusCalls = 0;
  send(strokes: readonly KeyStroke[]) {
    this.log.push(strokes.map(s => `${s.up ? "-" : "+"}${s.key.name}`).join(" "));
    return true;
  }
  typeText(text: string) {
    this.log.push(`type:${text}`);
    return true;
  }
  foregroundProcess() {
    return { pid: this.foreground.startsWith("FiveM") ? 77 : 12, name: this.foreground };
  }
  processes() {
    return this.running ? [{ pid: 77, name: "FiveM_b3258_GTAProcess.exe" }, { pid: 12, name: "explorer.exe" }] : [{ pid: 12, name: "explorer.exe" }];
  }
  focusProcessWindow() {
    this.focusCalls++;
    this.foreground = "FiveM_b3258_GTAProcess.exe";
    return true;
  }
}

async function controller(native: FakeNative, config?: string, overrides: Record<string, unknown> = {}) {
  const appData = await mkdtemp(join(tmpdir(), "fivedeck-"));
  await mkdir(join(appData, "CitizenFX"), { recursive: true });
  if (config !== undefined) await writeFile(join(appData, "CitizenFX", "fivem.cfg"), config);
  const logs: string[] = [];
  const game = new GameController({
    native: async () => native,
    settings: () => inputSettings(overrides),
    log: message => logs.push(message),
    appData,
    localAppData: appData,
    sleep: async () => undefined,
    processCacheMs: 0
  });
  return { game, appData, logs };
}

test("bridge commands write the file and tap F24 once the bind exists", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "unbindall\nbind KEYBOARD F24 \"exec fxd:/fivedeck.cfg\"\n");
  await game.run(["/e dance", "wait 500", "e c"], "bridge");
  assert.equal(await readFile(game.bridgeFile, "utf8"), "e dance\nwait 500\ne c\n");
  assert.deepEqual(native.log, ["+F24 -F24"]);
});

test("the first bridge command installs the bind through F8", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "unbindall\n");
  await game.run(["e sit"], "bridge");
  assert.deepEqual(native.log, ["+F8 -F8", 'type:bind keyboard F24 "exec fxd:/fivedeck.cfg"', "+RETURN -RETURN", "+F8 -F8", "+F24 -F24"]);
  native.log = [];
  await game.run(["e sit"], "bridge");
  assert.deepEqual(native.log, ["+F24 -F24"], "installed once per game session");
});

test("with automatic setup off, a missing bind is reported instead of installed", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "unbindall\n", { autoBridge: false });
  await assert.rejects(game.run(["e sit"], "bridge"), (error: unknown) => error instanceof DispatchError && error.reason === "bridge-missing");
  assert.deepEqual(native.log, []);
});

test("a bridge key that's already bound elsewhere is never overwritten", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "bind KEYBOARD F24 \"e salute\"\n");
  await assert.rejects(game.run(["e sit"], "bridge"), (error: unknown) => error instanceof DispatchError && error.reason === "bridge-conflict");
  assert.deepEqual(native.log, []);
});

test("no keys are sent unless the game is in the foreground", async () => {
  const native = new FakeNative();
  native.foreground = "WindowsTerminal.exe";
  const { game } = await controller(native, "");
  await assert.rejects(game.run(["e sit"], "console"), (error: unknown) => error instanceof DispatchError && error.reason === "not-focused");
  assert.deepEqual(native.log, []);
  native.running = false;
  await assert.rejects(game.run(["e sit"], "console"), (error: unknown) => error instanceof DispatchError && error.reason === "not-running");
});

test("focus-first brings the game forward before typing", async () => {
  const native = new FakeNative();
  native.foreground = "Discord.exe";
  const { game } = await controller(native, "", { focusGame: true });
  await game.run(["e sit"], "console");
  assert.equal(native.focusCalls, 1);
  assert.deepEqual(native.log, ["+F8 -F8", "type:e sit", "+RETURN -RETURN", "+F8 -F8"]);
});

test("chat transport opens chat per line and adds the slash", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "");
  await game.run(["me waves", "/e wave"], "chat");
  assert.deepEqual(native.log, ["+T -T", "type:/me waves", "+RETURN -RETURN", "+T -T", "type:/e wave", "+RETURN -RETURN"]);
  native.log = [];
  await game.chat("brb 5", false);
  assert.deepEqual(native.log, ["+T -T", "type:brb 5"]);
});

test("key holds press on down and always release on up", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "");
  const f13 = findKey("F13")!;
  await game.key(f13, ["shift"], "down");
  native.foreground = "chrome.exe";
  await game.key(f13, ["shift"], "up");
  assert.deepEqual(native.log, ["+LSHIFT +F13", "-F13 -LSHIFT"]);
});

test("presses are serialised so keystrokes never interleave", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "");
  await Promise.all([game.run(["a"], "console"), game.run(["b"], "console")]);
  assert.deepEqual(native.log.filter(entry => entry.startsWith("type:")), ["type:a", "type:b"]);
  assert.deepEqual(native.log.slice(0, 4), ["+F8 -F8", "type:a", "+RETURN -RETURN", "+F8 -F8"]);
});

test("offline install edits fivem.cfg only while the game is closed, with a backup", async () => {
  const native = new FakeNative();
  const { game } = await controller(native, "// generated by CitizenFX\nunbindall\n");
  assert.equal(await game.installBridgeOffline(), "game-running");
  native.running = false;
  assert.equal(await game.installBridgeOffline(), "installed");
  assert.equal(bindState(await readFile(game.configFile, "utf8"), "F24").state, "installed");
  assert.equal(await readFile(`${game.configFile}.fivedeck-backup`, "utf8"), "// generated by CitizenFX\nunbindall\n");
  assert.equal(await game.installBridgeOffline(), "installed");
  assert.equal(await game.bridgeState(), "installed");
});
